#define LEN 100
int Top_Down_Cut_Rod(int p[], int n) { /* 自顶向下 */
	int r = 0;
	int i;
	if (n == 0) {
		return 0;
	}
	for (i = 1; i <= n /* (1) 循环条件：切割长度 i 不超过钢条长度 n */; i++) {
		int tmp = p[i] + Top_Down_Cut_Rod(p, n - i);
		r = (r >= tmp) ? r : tmp;
	}
	return r;
}
int Bottom_Up_Cut_Rod(int p[], int n) { /* 自底向上 */
	int r[LEN] = { 0 };
	int temp = 0;
	int i, j;
	for (j = 1; j <= n; j++) {
		temp = 0;
		for (i = 1; i <= j /* (2) 内层循环条件：切割长度 i 不超过当前子问题长度 j */; i++) {
			temp = (temp >= p[i] + r[j - i]) ? temp : p[i] + r[j - i]; /* (3) 取当前最大收益：比较 temp 与第 i 段价格加剩余长度最优解之和 */
		}
		r[j] = temp; /* (4) 将长度 j 的最优收益存入数组 r */
	}
	return r[n];
}