#include <stdio.h>
#include <math.h>
#define N 4

/* 判断第 k 个皇后目前放置位置是否与前面的皇后冲突 */
int isplace(int pos[], int k) {
	int i;
	for (i = 1; i < k; i++)
		// (1) 判断是否同列冲突（pos[i] == pos[k]）或对角线冲突
		if (pos[i] == pos[k] || fabs(i - k) == fabs(pos[i] - pos[k]))
			return 0; // 有冲突，返回0
	return 1; // 无冲突，返回1
}

int bak12_main() {
	int i, j, count = 1;
	int pos[N + 1];

	// 初始化位置，所有皇后位置置为0
	for (i = 1; i <= N; i++)
		pos[i] = 0;

	// (2) 从第1个皇后开始摆放
	j = 1;

	while (j >= 1) {
		pos[j] = pos[j] + 1; // 将第j个皇后移到下一列

		/* 尝试摆放第 j 个皇后 */
		// (3) 当列未越界且当前位置与前面皇后冲突时，继续尝试下一列
		while (pos[j] <= N && !isplace(pos, j)) {
			pos[j] = pos[j] + 1;
		}

		/* 得到一个摆放方案 */
		if (pos[j] <= N && j == N) {
			printf("Solution%d:", count++); // 修复：将全角冒号"："改为英文冒号":"
			for (i = 1; i <= N; i++)
				printf("%d", pos[i]);
			printf("\n");
		}

		/* 考虑下一个皇后 */
		// (4) 当前皇后放置成功且还未放完所有皇后时，移到下一个皇后
		if (pos[j] <= N && j < N) {
			j = j + 1;
		}
		else { // 返回考虑上一个皇后
			pos[j] = 0; // 重置当前皇后位置
			// (5) 回溯到上一个皇后
			j = j - 1;
		}
	}
	return 0;
}